// Folha de conferência dos personagens: node episodios/ep01-elevador/folha_personagens.js
const path = require('path');
const fs = require('fs');
const { createCanvas, GlobalFonts } = require('@napi-rs/canvas');
const RAIZ = path.join(__dirname, '../..');
GlobalFonts.registerFromPath(path.join(RAIZ, 'assets/fontes/ArchivoBlack-Regular.ttf'), 'Archivo');
const P = require('./personagens');
const c = createCanvas(1920, 1080), g = c.getContext('2d');
g.fillStyle = '#5a5870'; g.fillRect(0, 0, 1920, 1080);
g.strokeStyle = '#000'; g.beginPath(); g.moveTo(0, 520); g.lineTo(1920, 520); g.stroke();
P.lurdesPerfil(g, 140, 520, {});
P.lurdesPerfil(g, 380, 520, { corpo: { x: 10, y: -60 }, pes: [{ x: 40, y: -110 }, { x: -8, y: -14 }], maos: [{ x: 80, y: -380 }, { x: 70, y: -300 }], olhoY: -0.8, vassoura: { topo: { x: 90, y: -520 }, base: { x: 70, y: -10 } } });
P.lurdesFrente(g, 640, 520, { sacola: true, chaves: true });
P.lurdesFrente(g, 860, 520, { sacola: true, maos: [{ x: -120, y: -230 }, { x: 70, y: -300 }], olhoX: -0.8, passo: 0.2 });
g.save(); g.translate(0, 520); g.scale(0.68, 0.68); g.translate(0, -520);
P.caioFrente(g, 1600, 520, { fone: 0, bob: 0.06 });
P.caioFrente(g, 1900, 520, { fone: 1, olhoX: 0.8 });
P.caioFrente(g, 2200, 520, { fone: 0.5, maos: [{ x: -96, y: -650 }, { x: 96, y: -650 }] });
P.caioFrente(g, 2500, 520, { fone: 1, maos: [null, { x: 56, y: -575 }], passo: 0.25 });
g.restore();
g.save(); g.scale(0.32, 0.32);
P.lurdesClose(g, 700, 2350, { olhoY: -0.6 });
P.maoCorrimao(g, 1100, 3150, 1, true);
P.caioClose(g, 2200, 2350, { fone: 0 });
P.caioClose(g, 3600, 2350, { fone: 1, mao: { x: 150, y: 260 }, sobr: 0.6, sobrInc: 0.6 });
P.caioClose(g, 5000, 2350, { fone: 0.5, mao: { x: 270, y: 160 } });
g.restore();
const out = path.join(RAIZ, 'saida/ep01-elevador'); fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'folha_personagens.png'), c.toBuffer('image/png'));
console.log('ok', P.FALTA);
